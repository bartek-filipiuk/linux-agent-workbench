import {chromium} from '/home/bartek/linux-agent/services/browser-worker/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import {performance} from 'node:perf_hooks';
const start=performance.now();
const root='/home/bartek/linux-agent-tutorial-04';
const url='file:///home/bartek/linux-agent-tutorial-landing-workspace/index.html';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(String(e)));page.on('requestfailed',r=>errors.push(r.url()+': '+r.failure()?.errorText));page.on('request',r=>requests.push(r.url()));
const checks={};
await page.goto(url);await page.evaluate(()=>document.fonts.ready);
checks.oneH1=await page.locator('h1').count()===1;
checks.desktopNoOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);
checks.localFonts=await page.evaluate(()=>document.fonts.check('16px Outfit')&&document.fonts.check('16px "DM Sans"'));
checks.fourSourcesThreePublishers=await page.locator('#sources a').evaluateAll(a=>{const u=[...new Set(a.map(n=>n.href))];return u.length>=4&&new Set(u.map(x=>new URL(x).hostname)).size>=3});
checks.anchorsResolve=await page.locator('a[href^="#"]').evaluateAll(a=>a.every(n=>document.getElementById(n.getAttribute('href').slice(1))));
await page.screenshot({path:root+'/output/landing-desktop.png',fullPage:true});
await page.screenshot({path:root+'/output/landing-hero.png'});
await page.locator('.btn-primary').click();await page.waitForTimeout(200);
checks.ctaNavigates=await page.evaluate(()=>location.hash==='#checklist');
const boxes=page.locator('input[type=checkbox]');checks.fiveChecklistItems=await boxes.count()===5;
for(let i=0;i<5;i++){await boxes.nth(i).focus();await page.keyboard.press('Space');}
checks.keyboardChecklist=await page.locator('#progressCount').innerText()==='5';
await page.locator('#resetChecklist').click();checks.reset=await page.locator('#progressCount').innerText()==='0'&&await page.locator('input[type=checkbox]:checked').count()===0;
const slider=page.locator('#compareSlider');await slider.focus();await page.keyboard.press('Home');
checks.sliderDark=await slider.inputValue()==='0'&&(await slider.getAttribute('aria-valuetext')).includes('dark sky only');
const darkClip=await page.locator('.compare-layer--bright').evaluate(n=>getComputedStyle(n).clipPath);
await page.keyboard.press('End');checks.sliderBright=await slider.inputValue()==='100'&&(await slider.getAttribute('aria-valuetext')).includes('light-polluted sky only');
checks.sliderActuallyChangesImage=darkClip!==await page.locator('.compare-layer--bright').evaluate(n=>getComputedStyle(n).clipPath);
checks.visibleFocus=await slider.evaluate(n=>getComputedStyle(n).outlineStyle!=='none');
await page.setViewportSize({width:390,height:844});await page.goto(url);await page.evaluate(()=>document.fonts.ready);
checks.mobileNoOverflow=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth);
await page.screenshot({path:root+'/output/landing-mobile.png',fullPage:true});
await context.setOffline(true);await page.reload();await page.evaluate(()=>document.fonts.ready);
checks.offlineContent=await page.locator('h1').isVisible()&&await page.locator('svg').count()>0;
checks.noRemoteAssets=requests.every(x=>!/^https?:/.test(x));
const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});const np=await nojs.newPage();await np.goto(url);
checks.contentWithoutJS=await np.locator('h1').isVisible()&&await np.locator('#tips').innerText().then(x=>x.length>150);
checks.noBrowserErrors=errors.length===0;
const report={checkedAt:new Date().toISOString(),elapsedSeconds:(performance.now()-start)/1000,checks,allPassed:Object.values(checks).every(Boolean),errors,scope:'Independent host Chromium check of generated HTML, outside the app task clock. Not a full accessibility or factual audit.'};
fs.writeFileSync(root+'/evidence/browser-check.json',JSON.stringify(report,null,2));
await browser.close();console.log(JSON.stringify(report,null,2));
